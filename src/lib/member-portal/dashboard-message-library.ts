export type DashboardMessageEntry = {
  key: string;
  category: DashboardMessageCategory;
  template: string;
};

function buildCategory(
  category: DashboardMessageCategory,
  templates: string[],
): DashboardMessageEntry[] {
  return templates.map((template, index) => ({
    key: `${category}:${index}`,
    category,
    template,
  }));
}

